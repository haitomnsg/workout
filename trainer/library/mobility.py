"""Warm-up, cool-down and rest-day mobility moves.

These are timed: the app runs them hands-free, one after another, with a
countdown and a voice cue to switch sides. `seconds` is the time per side for
`per_side` moves.
"""
from __future__ import annotations

from . import Move, register


def W(id: str, name: str, slug: str, seconds: int, how: tuple[str, ...], **kw) -> Move:
    return Move(id=id, name=name, slug=slug, kind="warmup", group="warmup",
                seconds=seconds, steps=how, **kw)


def ST(id: str, name: str, slug: str, seconds: int, how: tuple[str, ...], **kw) -> Move:
    return Move(id=id, name=name, slug=slug, kind="stretch", group="stretch",
                seconds=seconds, steps=how, **kw)


def MO(id: str, name: str, slug: str, seconds: int, how: tuple[str, ...], **kw) -> Move:
    return Move(id=id, name=name, slug=slug, kind="mobility", group="mobility",
                seconds=seconds, steps=how, **kw)


